-- ---------------------------------------------------------------------------
-- 메시지에 종류를 준다 — 배송 정보 카드 (F6 3.6)
--
-- 낙찰자가 저장해 둔 배송지(이름 · 연락처 · 주소)를 **메시지 한 건**으로 보낸다.
-- 주최자가 `addresses` 를 읽는 것이 아니라 낙찰자가 자기 정보를 복사해 보내는
-- 것이므로, `addresses_select_own` 네 정책은 그대로 둔다.
--
-- 값을 메시지에 복사해 두면 **보낸 시점의 스냅샷**이 남는다. 낙찰자가 나중에
-- 배송지를 고쳐도 이미 보낸 정보는 그대로다 — 송장을 쓴 시점의 주소가 남아야
-- 한다.
--
-- `content` 에는 사람이 읽을 수 있는 형태를 그대로 넣는다. 카드가 그려지지 않는
-- 어떤 경로로 보더라도 내용은 읽혀야 한다.
-- ---------------------------------------------------------------------------

alter table public.messages
  add column kind text not null default 'TEXT'
  check (kind in ('TEXT', 'ADDRESS'));

comment on column public.messages.kind is
  'TEXT = 일반 대화, ADDRESS = 낙찰자가 보낸 배송 정보. content 는 두 경우 모두 사람이 읽는 본문이다 (F6 3.6)';

-- UPDATE 는 여전히 `content` 만 열려 있다. 보낸 뒤 종류를 바꿀 수 있으면
-- 일반 메시지를 배송 정보로 둔갑시킬 수 있다.
