-- users.onboarded_at 을 되돌린다 (F11 3.3 재개정, 20260803000001 을 대체)
--
-- 온보딩을 **로그인 이후**에 한 번 보여주려고 계정에 기록을 남겼다. 그런데
-- 온보딩이 하는 일은 "사연으로 입찰한다"는 낯선 개념을 이해시키는 것이고,
-- 그건 **가입을 결정하기 전에** 나와야 하는 이야기다. 로그인 뒤에 보여주면
-- 이미 결정한 사람에게 설명하는 셈이었다.
--
-- 로그인 전으로 옮기고 나니 판정 자체가 필요 없어졌다.
--
--   로그인함   → 메인
--   로그아웃함 → 온보딩 → 로그인 화면
--
-- 로그아웃 상태로 진입 화면에 오는 일이 드물어서(둘러보기를 누른 사람은
-- /main 에 있고, 하단 탭 어디도 / 로 가지 않는다) 다시 보게 될 일이 거의 없다.
-- 그 드문 경우를 막으려고 컬럼 하나와 콜백 분기를 두는 것은 값이 맞지 않는다.
--
-- 컬럼을 남겨두지 않는 이유는 **아무도 읽지도 쓰지도 않기 때문이다.** 쓰이지
-- 않는 컬럼은 다음에 읽는 사람에게 "이건 뭘 위한 거지"를 묻게 만든다.
-- ---------------------------------------------------------------------------

revoke update (onboarded_at) on public.users from authenticated;

alter table public.users
  drop column onboarded_at;
