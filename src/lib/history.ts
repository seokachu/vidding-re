/**
 * 돌아갈 히스토리가 있는가.
 *
 * `router.back()` 은 히스토리가 없으면 **아무 일도 하지 않는다.** 공유 링크나
 * 푸시 알림으로 상세에 바로 들어온 사람에게는 뒤로가기 버튼이 죽은 것처럼
 * 보인다. 그때는 부르는 쪽이 그 화면이 속한 탭으로 `replace` 한다
 * (`tabRootOf`, 기능명세서 X8).
 *
 * `history.length` 는 이 탭의 세션 히스토리 전체라 다른 사이트 항목도 센다.
 * 브라우저에서는 그 사이트로 돌아가는 것이 곧 브라우저의 뒤로가기이니 맞고,
 * 앱 셸 안에서는 전부 우리 페이지라 정확하다. 클라이언트에서만 부른다.
 */
export function hasHistory(): boolean {
  return window.history.length > 1;
}
